/**
 * Returns the realistic WebP product image for any phone model.
 */
export function getPhoneImage(model = '', brand = 'Apple') {
  if (!model) {
    return brand.toLowerCase() === 'samsung'
      ? '/phones/samsung-s-series.webp'
      : '/phones/iphone-16-pro-max.webp';
  }

  // Exact lookup in predefined models
  const allPhones = [...IPHONE_MODELS, ...SAMSUNG_CATEGORIES];
  const directMatch = allPhones.find(
    (p) => p.model.toLowerCase() === model.toLowerCase() || p.id === model.toLowerCase()
  );
  if (directMatch) return directMatch.image;

  // Fuzzy model matching
  const m = model.toLowerCase();
  if (m.includes('galaxy') || m.includes('samsung') || brand.toLowerCase() === 'samsung') {
    if (m.includes('fold') || m.includes('flip') || m.includes('z series')) return '/phones/samsung-z-series.webp';
    if (m.includes('a55') || m.includes('a54') || m.includes('a35') || m.includes('a series')) return '/phones/samsung-a-series.webp';
    return '/phones/samsung-s-series.webp';
  }

  if (m.includes('air')) return '/iphone%20model%20images/iphone_air.jpg';
  if (m.includes('17e')) return '/iphone%20model%20images/iphone17e.jpg';
  if (m.includes('18')) {
    return m.includes('pro max') ? '/iphone%20model%20images/iphone_18_pro_max.jpg' : '/iphone%20model%20images/iphone_18_pro.jpg';
  }
  if (m.includes('17')) {
    if (m.includes('pro max')) return '/iphone%20model%20images/iphone17_pro_max.jpg';
    if (m.includes('pro')) return '/iphone%20model%20images/iphone_17_pro.jpg';
    return '/iphone%20model%20images/iphone_17.jpg';
  }
  if (m.includes('16')) {
    if (m.includes('pro max')) return '/iphone%20model%20images/iphone16_pro_max.jpg';
    if (m.includes('pro')) return '/iphone%20model%20images/iphone16_pro.jpg';
    if (m.includes('plus')) return '/iphone%20model%20images/iphone16_plus.jpg';
    return '/iphone%20model%20images/iphone16.jpg';
  }
  if (m.includes('15')) {
    if (m.includes('pro max')) return '/iphone%20model%20images/iphone15_pro_max.jpg';
    if (m.includes('pro')) return '/iphone%20model%20images/iphone15_pro.jpg';
    if (m.includes('plus')) return '/iphone%20model%20images/iphone15_plus.jpg';
    return '/iphone%20model%20images/iphone15.jpg';
  }
  if (m.includes('14')) {
    if (m.includes('pro max')) return '/iphone%20model%20images/iphone14_pro_max.jpg';
    if (m.includes('pro')) return '/iphone%20model%20images/iphone14_pro.jpg';
    if (m.includes('plus')) return '/iphone%20model%20images/iphone14_plus.jpg';
    return '/iphone%20model%20images/iphone14.jpg';
  }
  if (m.includes('13')) {
    if (m.includes('pro max')) return '/iphone%20model%20images/iphone13_pro_max.jpg';
    if (m.includes('pro')) return '/iphone%20model%20images/iphone13_pro.jpg';
    return '/iphone%20model%20images/iphone13.jpg';
  }
  if (m.includes('pro max')) return '/iphone%20model%20images/iphone16_pro_max.jpg';
  if (m.includes('pro')) return '/iphone%20model%20images/iphone16_pro.jpg';
  return '/iphone%20model%20images/iphone16.jpg';
}
